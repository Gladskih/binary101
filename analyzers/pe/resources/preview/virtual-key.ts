export const formatVirtualKey = (key: number): string => {
  if (key >= 0x70 && key <= 0x87) return `F${key - 0x6f}`;
  if ((key >= 0x30 && key <= 0x39) || (key >= 0x41 && key <= 0x5a)) {
    return String.fromCharCode(key);
  }
  return virtualKeys.get(key) ?? `VK_0x${key.toString(16).padStart(2, "0")}`;
};
